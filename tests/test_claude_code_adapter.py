def test_detect_finds_the_sessions_and_the_version(
    adapter: ClaudeCodeAdapter, source: Path
) -> None:
    """The version reported is the last one in the most recently touched session.

    ``basic.jsonl`` spans an upgrade from 2.1.234 to 2.1.237 — as the real data
    did — so this also pins down which end of the file is read.
    """
    newest = source / "projects" / "C--Users-sample-Projects-widget" / f"{BASIC_ID}.jsonl"
    os.utime(newest, (2_000_000_000, 2_000_000_000))

    result = adapter.detect()

    assert result.installed is True
    # Three transcripts, one with no messages in it. The count is of
    # conversations, not files -- see ferry.adapters.census.
    assert result.conversation_count_estimate == 2
    assert any("1 empty" in note for note in result.notes)
    assert result.version == "2.1.237"
    assert any("2 project directories" in note for note in result.notes)


