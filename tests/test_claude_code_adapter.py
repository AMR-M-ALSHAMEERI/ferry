def install(root: Path, fixture: str, session_id: UUID, cwd: str) -> Path:
    """Lay a fixture out the way Claude Code would have on disk."""
    from ferry.adapters.claude_code.paths import mangle

    project = root / "projects" / mangle(cwd)
    project.mkdir(parents=True, exist_ok=True)
    destination = project / f"{session_id}.jsonl"
    destination.write_bytes((FIXTURES / fixture).read_bytes())
    return destination


