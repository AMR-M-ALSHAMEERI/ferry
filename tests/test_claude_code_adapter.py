def test_the_first_matching_remap_rule_wins() -> None:
    rules = (("/a/b", "/first"), ("/a", "/second"))
    assert remap_prefix("/a/b/c", rules) == "/first/c"
    assert remap_prefix("/a/x", rules) == "/second/x"


