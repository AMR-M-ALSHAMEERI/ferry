def test_export_is_resumable(adapter: ClaudeCodeAdapter, tmp_path: Path) -> None:
    """A second run must skip what the first wrote rather than redo it."""
    list(adapter.export(tmp_path / "bundle"))
    stamp = (tmp_path / "bundle" / "conversations" / f"{BASIC_ID}.json").read_bytes()

    events = list(adapter.export(tmp_path / "bundle"))

    assert [e.message for e in events if e.kind == "progress"] == []
    assert sum(1 for e in events if e.kind == "skipped") == 3
    assert (tmp_path / "bundle" / "conversations" / f"{BASIC_ID}.json").read_bytes() == stamp


def test_export_does_not_touch_the_source(
    adapter: ClaudeCodeAdapter, source: Path, tmp_path: Path
) -> None:
    """The single most important safety property in the project (PLAN.md §6.8.2)."""
    before = {path: sha256_file(path) for path in sorted(source.rglob("*")) if path.is_file()}

    list(adapter.export(tmp_path / "bundle"))

    after = {path: sha256_file(path) for path in sorted(source.rglob("*")) if path.is_file()}
    assert after == before


